"""Re-execute ONE executed notebook (the 100x-64 recipe, per-notebook edition).

The full driver (scratch/reexecute_all_notebooks_64.py) re-runs all eight
in one process -- too long for one shell call on this 4 GB sandbox, so
this variant takes a notebook name and re-executes just that one (the
per-notebook write happens immediately, so chunked invocations are safe).
The no-output twins are regenerated by the caller once every notebook is
done (scratch/strip_notebook_outputs.py).

Run from the toolkit root:

    python scratch/reexecute_nb_162.py complete_ml_workflow.ipynb
"""
from __future__ import annotations

import os
import sys
import sysconfig
import time
from pathlib import Path

for _var in ("LOKY_MAX_CPU_COUNT", "OMP_NUM_THREADS", "MKL_NUM_THREADS",
             "OPENBLAS_NUM_THREADS"):
    os.environ.setdefault(_var, "1")
os.environ.pop("MPLBACKEND", None)

import nbformat
from nbclient import NotebookClient

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"
_SITE_PACKAGES = sysconfig.get_paths()["purelib"]


def main() -> int:
    name = sys.argv[1]
    path = EXAMPLES / name
    nb = nbformat.read(path, as_version=4)
    for cell in nb.cells:
        if cell.cell_type == "code":
            cell.outputs = []
            cell.execution_count = None
    started = time.perf_counter()
    client = NotebookClient(
        nb,
        timeout=2400,
        kernel_name="python3",
        resources={"metadata": {"path": str(EXAMPLES)}},
    )
    client.execute()
    for cell in nb.cells:
        for output in cell.get("outputs", []):
            if output.get("output_type") == "stream":
                raw = output.get("text", "")
                if isinstance(raw, str):
                    raw = [raw]
                joined = "".join(
                    t.replace(_SITE_PACKAGES + "/", "site-packages/")
                    for t in raw
                )
                output["text"] = joined.splitlines(keepends=True)
    nbformat.write(nb, path)

    code_cells = [c for c in nb.cells if c.cell_type == "code"]
    executed = sum(1 for c in code_cells if c.get("execution_count"))
    errors = [o for c in code_cells for o in c.get("outputs", [])
              if o.output_type == "error"]
    figures = sum(1 for c in code_cells for o in c.get("outputs", [])
                  if o.get("data", {}).get("image/png"))
    if errors or executed != len(code_cells):
        print(f"FAIL {name}: {len(errors)} error(s), "
              f"{executed}/{len(code_cells)} cells")
        return 1
    print(f"executed {name}: {len(code_cells)} code cells, "
          f"{figures} figures, {time.perf_counter() - started:.0f} s",
          flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
