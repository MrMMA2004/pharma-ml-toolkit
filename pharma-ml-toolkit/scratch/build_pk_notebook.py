def main() -> int:
    nb = nbformat.v4.new_notebook(cells=build_cells())

    # Carry the same kernel metadata as the other two trilogy notebooks.
    template = nbformat.read(
        ROOT / "examples" / "complete_ml_workflow.ipynb", as_version=4
    )
    nb.metadata = template.metadata

    # Execute the whole notebook with committed outputs (worker caps keep
    # the sandbox's tight memory envelope safe).
    os.environ.update(
        {
            "LOKY_MAX_CPU_COUNT": "1",
            "OMP_NUM_THREADS": "1",
            "OPENBLAS_NUM_THREADS": "1",
            "MKL_NUM_THREADS": "1",
        }
    )
    client = NotebookClient(nb, timeout=900, kernel_name="python3")
    client.execute()

    nbformat.write(nb, NOTEBOOK)

    # Sanity report
    code_cells = [c for c in nb.cells if c.cell_type == "code"]
    errors = [
        out
        for c in code_cells
        for out in c.get("outputs", [])
        if out.get("output_type") == "error"
    ]
    figures = sum(
        1
        for c in code_cells
        for out in c.get("outputs", [])
        if "image/png" in out.get("data", {})
    )
    print(f"cells: {len(nb.cells)} | code: {len(code_cells)} | "
          f"markdown: {len(nb.cells) - len(code_cells)}")
    print(f"error outputs: {len(errors)} | inline figures: {figures}")
    print(f"file size: {NOTEBOOK.stat().st_size / 1024:.0f} KB")
    if errors:
        for err in errors[:3]:
            print("ERROR:", err.get("ename"), str(err.get("evalue"))[:200])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
