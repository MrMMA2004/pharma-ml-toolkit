PD = """\
## 8 · PD — the Emax family

Pharmacodynamics in one parameterisation: effect rises toward `Emax` with
concentration, `EC50` marks the halfway point, and the Hill coefficient
bends the curve (steeper than 1 = switch-like). The inhibitory form runs
the same logic downward — baseline minus inhibition, `IC50` where the
effect is half the maximum — and `linear_effect` is the honest fallback
when the data has seen nothing but a straight line.

`ec50_for_target_effect` inverts the model: give it the effect you *want*
(80 % of Emax) and it returns the concentration that achieves it — target
concentration design in one call. `effect_table` renders the same model
as a ready-to-report table.
"""

