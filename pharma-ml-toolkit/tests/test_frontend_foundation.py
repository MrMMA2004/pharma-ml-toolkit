def test_generated_types_cover_every_contract_schema():
    contract = json.loads(
        (ROOT / "contracts" / "openapi.json").read_text()
    )
    schemas = sorted(contract.get("components", {}).get("schemas", {}))
    assert schemas, "the committed contract has no component schemas"
    generated = (FRONTEND / "src" / "types" / "api.d.ts").read_text()
    missing = [s for s in schemas if f"{s}:" not in generated]
    assert not missing, (
        "src/types/api.d.ts is stale against contracts/openapi.json — "
        f"re-run `npm run generate:types`; missing: {missing[:8]}"
    )


def test_production_frontend_is_offline_only():
    html = (FRONTEND / "index.html").read_text()
    # the CSP: no remote script/style sources (self + the loopback
    # API/WS endpoints only)
    assert "script-src 'self'" in html
    assert "https:" not in html.split("script-src", 1)[1].split(";")[0]
    # no CDN script/link tags at all
    for line in html.splitlines():
        if "<script" in line and "src=" in line and "/src/" not in line:
            assert "http" not in line, f"remote script tag: {line.strip()}"
    vite_config = (FRONTEND / "vite.config.ts").read_text()
    assert '"dist"' in vite_config or "outDir" in vite_config
    assert "https://" not in vite_config, (
        "vite.config.ts must not point the production build at a remote URL"
    )
