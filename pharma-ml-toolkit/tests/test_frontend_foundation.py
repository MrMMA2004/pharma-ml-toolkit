"""part11 Phase Three — the frontend foundation drift guards.

The frontend/ SPA is a Node-toolchain product; the Python gate cannot
run vite, but it CAN — and must — keep the foundation honest:

* the mandated stack (§3) is pinned in package.json: TypeScript,
  React, Vite, Tailwind CSS, Motion (the maintained Framer Motion
  API), Plotly.js, Three.js — plus the shadcn/ui Radix foundation;
* the generated API types (`src/types/api.d.ts`) cover EVERY schema
  in the current committed OpenAPI contract (§12.2: one DTO source,
  regenerated by `npm run generate:types` — a schema added backend-
  side without re-export turns this suite red, twice: the contract
  drift gate and this one);
* the workspace registry carries the EXACT §10.1 navigation order and
  marks Introduction as the initial page (§10.1: Introduction-only
  start page, no nine-card dashboard return);
* the TypeScript config is strict where it matters (strict,
  noUncheckedIndexedAccess);
* the production frontend is offline-only: the CSP in index.html
  allows no remote script/style sources, and vite.config declares the
  local `dist` outDir with no remote URLs.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "frontend"

MANDATED_DEPS = {
    "typescript": "dev",
    "vite": "dev",
    "tailwindcss": "dev",
    "react": "dep",
    "react-dom": "dep",
    "motion": "dep",
    "plotly.js-dist-min": "dep",
    "three": "dep",
}

# part11 §10.1 — the exact left-to-right navigation order.
EXPECTED_ORDER = [
    "Introduction",
    "Datasets",
    "Machine Learning",
    "Deep Learning",
    "Generative AI",
    "Molecular Docking",
    "PK/PD",
    "Molecular Dynamics Analysis",
    "Visualization",
]


def _package_json() -> dict:
    return json.loads((FRONTEND / "package.json").read_text())


def test_mandated_stack_is_pinned():
    pkg = _package_json()
    deps = pkg.get("dependencies", {})
    dev_deps = pkg.get("devDependencies", {})
    for name, kind in MANDATED_DEPS.items():
        pool = deps if kind == "dep" else dev_deps
        assert name in pool, f"the mandated stack lacks {name!r} in {kind}s"


def test_shadcn_radix_foundation_present():
    pkg = _package_json()
    deps = pkg.get("dependencies", {})
    assert any(dep.startswith("@radix-ui/") for dep in deps), (
        "the shadcn/ui foundation is the Radix heads — no @radix-ui/* "
        "dependency means the primitives would be hand-rolled"
    )
    # the shadcn idiom's class-merge pair
    assert "clsx" in deps and "tailwind-merge" in deps
    assert "class-variance-authority" in deps


def test_workspace_order_is_the_exact_101_sequence():
    registry = (FRONTEND / "src" / "app" / "workspaces.ts").read_text()
    # the labels must appear in the registry in the exact §10.1 order
    positions = [registry.find(f'"{label}"') for label in EXPECTED_ORDER]
    assert all(p >= 0 for p in positions), (
        "a §10.1 workspace label is missing from the registry: "
        f"{[label for label, p in zip(EXPECTED_ORDER, positions) if p < 0]}"
    )
    assert positions == sorted(positions), (
        "the workspace registry order diverges from the §10.1 sequence"
    )
    # the exported order constant agrees
    order_literal = registry.find("WORKSPACE_ORDER")
    assert order_literal >= 0
    assert 'INITIAL_WORKSPACE: WorkspaceId = "introduction"' in registry


