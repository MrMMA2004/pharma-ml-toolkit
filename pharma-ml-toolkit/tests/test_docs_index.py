"""Drift guard: keep ``docs/INDEX.md`` in sync with the live ``pharmaml`` API.

``docs/INDEX.md`` is auto-generated by ``scratch/build_docs_index.py``.  These
tests parse the generated markdown and compare it against the imported package,
so that adding, removing or renaming a public symbol without regenerating the
index — or misclassifying a symbol's kind — fails the suite instead of silently
shipping stale documentation.

If they fail, regenerate the index from the repository root::

    python scratch/build_docs_index.py
"""

from __future__ import annotations

import importlib
import inspect
import re
import sys
from pathlib import Path
from typing import Any

import pytest

# ---------------------------------------------------------------------------
# Robust filesystem location
# ---------------------------------------------------------------------------
# tests/ -> parent is the package root, independent of the current working
# directory or the pytest rootdir, so the suite works when run from the
# package directory (``python -m pytest tests/ -q``) and from anywhere else.
TESTS_DIR = Path(__file__).resolve().parent
PACKAGE_ROOT = TESTS_DIR.parent
INDEX_MD = PACKAGE_ROOT / "docs" / "INDEX.md"
SRC_DIR = PACKAGE_ROOT / "src"

# pyproject.toml sets ``pythonpath = ["src"]`` for pytest, so ``import
# pharmaml`` already works under the test runner.  The guarded insert below is
# a safety net for executions outside that configuration (e.g. running this
# single file without the ini options being picked up).
if SRC_DIR.is_dir() and str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

REGENERATE_HINT = (
    "Regenerate the index from the repository root with:\n"
    "    python scratch/build_docs_index.py"
)

#: Modules that must always keep a section in the index (the public
#: top-level modules plus the two documented ``utils`` submodules).
REQUIRED_MODULES: tuple[str, ...] = (
    "pharmaml",
    "pharmaml.data",
    "pharmaml.chem",
    "pharmaml.ml",
    "pharmaml.generative",
    "pharmaml.biology",
    "pharmaml.pharma",
    "pharmaml.docking",
    "pharmaml.utils.io",
    "pharmaml.utils.validation",
)

#: Symbol kinds the generator can emit (mirrors scratch/build_docs_index.py).
KNOWN_KINDS: tuple[str, ...] = ("class", "function", "module", "constant")

_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_DOTTED_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*$")
_HEADING = re.compile(r"^#{1,6}\s+(.+?)\s*$")
_ALIGNMENT_CELL = re.compile(r":?-{2,}:?")


def _clean_cell(cell: str) -> str:
    """Strip markdown decoration (padding and backticks) from a table cell."""
    return cell.strip().strip("`").strip()


def parse_index(markdown: str) -> tuple[dict[str, dict[str, str]], list[str]]:
    """Parse INDEX.md content into ``{module: {symbol: kind}}``.

    The parser is tolerant to markdown formatting — any heading level, missing
    backticks, extra whitespace, pipes inside summary cells, and fenced code
    blocks (the CLI section) are all handled — but strict about symbol names
    (valid Python identifiers, no duplicates) and kinds.

    Returns the module map plus a list of human-readable problems found while
    parsing (empty when the file is well formed).
    """
    modules: dict[str, dict[str, str]] = {}
    problems: list[str] = []
    current: str | None = None
    in_fence = False

    for line in markdown.splitlines():
        stripped = line.strip()

        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:  # fenced blocks (e.g. the CLI usage block) are not tables
            continue

        heading = _HEADING.match(line)
        if heading:
            title = _clean_cell(heading.group(1))
            if _DOTTED_NAME.match(title):  # a Python module section
                if title in modules:
                    problems.append(f"duplicate section for module `{title}`")
                else:
                    modules[title] = {}
                current = title
            else:  # e.g. "Command-line interface" — not a module section
                current = None
            continue

        if current is None or not stripped.startswith("|"):
            continue  # prose / blurb lines are irrelevant

        if all(_ALIGNMENT_CELL.match(cell.strip()) for cell in stripped.strip("|").split("|")):
            continue  # markdown alignment row (|---|---|---|)

        # Split into at most (name, kind, summary) so pipes inside a summary
        # cannot break the row apart.
        cells = stripped.strip("|").split("|", 2)
        if len(cells) < 2 or not _clean_cell(cells[0]):
            continue  # not a symbol row
        name = _clean_cell(cells[0])
        kind = _clean_cell(cells[1])

        if name.lower() == "symbol" and kind.lower() == "kind":
            continue  # table header row

        if not _IDENTIFIER.match(name):
            problems.append(f"{current}: symbol name {name!r} is not a valid identifier")
            continue
        if kind not in KNOWN_KINDS:
            problems.append(f"{current}: symbol {name!r} has unknown kind {kind!r}")
            continue
        if name in modules[current]:
            problems.append(f"{current}: duplicate symbol row for {name!r}")
            continue
        modules[current][name] = kind

    return modules, problems


def public_names(module: Any) -> list[str]:
    """Public symbol names of ``module``: its ``__all__`` when declared, else
    the public (non-underscore) names from ``dir()``."""
    declared = getattr(module, "__all__", None)
    if declared is not None:
        return list(declared)
    return [name for name in dir(module) if not name.startswith("_")]


def classify(obj: Any) -> str:
    """Classify ``obj`` exactly the way the docs generator does."""
    if inspect.isclass(obj):
        return "class"
    if inspect.isroutine(obj) or inspect.isfunction(inspect.unwrap(obj)):
        # ``unwrap`` covers decorated callables such as functools.lru_cache
        # (a plain ``isfunction`` check misclassifies those as constants).
        return "function"
    if inspect.ismodule(obj):
        return "module"
    return "constant"


def _load_index() -> tuple[dict[str, dict[str, str]], list[str]]:
    if not INDEX_MD.is_file():
        return {}, []
    return parse_index(INDEX_MD.read_text(encoding="utf-8"))


INDEX_MODULES, PARSE_PROBLEMS = _load_index()
DOCUMENTED_MODULES = sorted(INDEX_MODULES)


# ---------------------------------------------------------------------------
# Structural checks
# ---------------------------------------------------------------------------
def test_docs_index_exists() -> None:
    """INDEX.md must exist; tell the developer how to (re)generate it."""
    if not INDEX_MD.is_file():
        pytest.fail(
            f"docs/INDEX.md is missing (expected at {INDEX_MD}).\n{REGENERATE_HINT}"
        )
    assert INDEX_MD.stat().st_size > 0, f"docs/INDEX.md at {INDEX_MD} is empty."


def test_index_rows_are_well_formed() -> None:
    """Every symbol row must parse into a valid name + known kind."""
    assert not PARSE_PROBLEMS, (
        "Malformed rows found while parsing docs/INDEX.md:\n- "
        + "\n- ".join(PARSE_PROBLEMS)
        + f"\n{REGENERATE_HINT}"
    )


def test_index_documents_the_core_modules() -> None:
    """The index must keep a section for every core public module."""
    assert INDEX_MODULES, f"No module sections found in {INDEX_MD}.\n{REGENERATE_HINT}"
    missing = [name for name in REQUIRED_MODULES if name not in INDEX_MODULES]
    assert not missing, (
        f"docs/INDEX.md no longer documents {missing}. If this is intentional, "
        "update MODULES in scratch/build_docs_index.py and REQUIRED_MODULES in "
        f"tests/test_docs_index.py, then regenerate.\n{REGENERATE_HINT}"
    )


def test_documented_modules_are_importable() -> None:
    """Every module section must correspond to a real importable module."""
    problems: list[str] = []
    for name in INDEX_MODULES:
        try:
            importlib.import_module(name)
        except Exception as exc:  # noqa: BLE001 — report every import failure, not the first
            problems.append(f"{name}: {exc!r}")
    assert not problems, (
        "docs/INDEX.md documents modules that cannot be imported:\n- "
        + "\n- ".join(problems)
    )


# ---------------------------------------------------------------------------
# Drift checks (per documented module)
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("module_name", DOCUMENTED_MODULES)
def test_index_symbols_match_live_api(module_name: str) -> None:
    """The documented symbol set must exactly equal the module's public API."""
    module = importlib.import_module(module_name)
    documented = set(INDEX_MODULES[module_name])
    live = set(public_names(module))

    missing_from_docs = sorted(live - documented)
    stale_in_docs = sorted(documented - live)

    details: list[str] = []
    if missing_from_docs:
        details.append(
            "public but missing from INDEX.md: " + ", ".join(missing_from_docs)
        )
    if stale_in_docs:
        details.append(
            "listed in INDEX.md but no longer public: " + ", ".join(stale_in_docs)
        )
    assert not details, (
        f"docs/INDEX.md is out of sync with the live API of `{module_name}` "
        f"(source: {getattr(module, '__file__', '?')}):\n"
        + "\n".join(f"- {line}" for line in details)
        + f"\n{REGENERATE_HINT}"
    )


@pytest.mark.parametrize("module_name", DOCUMENTED_MODULES)
def test_index_kinds_match_live_objects(module_name: str) -> None:
    """Documented kinds must match live inspection of each symbol."""
    module = importlib.import_module(module_name)
    mismatches: list[str] = []

    for name, documented_kind in INDEX_MODULES[module_name].items():
        if not hasattr(module, name):
            mismatches.append(f"{module_name}.{name}: listed in INDEX.md but not importable")
            continue
        live_kind = classify(getattr(module, name))
        if live_kind != documented_kind:
            mismatches.append(
                f"{module_name}.{name}: INDEX.md says {documented_kind!r}, "
                f"live object is {live_kind!r}"
            )

    assert not mismatches, (
        "Kind classification drift between docs/INDEX.md and the live package:\n"
        + "\n".join(f"- {line}" for line in mismatches)
        + f"\n{REGENERATE_HINT}"
    )
