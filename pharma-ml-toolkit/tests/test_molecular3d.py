"""part11 Phase Eighteen — the Three.js 3D scientific visualization
lane, the drift guards.

The Python gate cannot execute the React viewer, but every contract
the lane rides CAN be pinned against the sources that define it, so a
backend-side or vocabulary-side rename turns into a red test before
the frontend drifts:

* the PDBQT parser's grammar vs the backend's own column convention
  (``tests/conftest.py::pdbqt_atom`` — cols 31-54 = xyz, the trailing
  token = the AutoDock type): the round-trip is exercised live against
  a generated record, plus the source-text pins of the exact slices;
* the element vocabulary: the AutoDock type → element map (A→C,
  OA→O, HD→H, NA→N, SA→S …), the CPK palette, the display and
  covalent radii, the bond-inference atom limit;
* the viewer component's Phase Eighteen contract: three + OrbitControls
  imports, the resource-awareness blocks (pixel-ratio cap, the
  IntersectionObserver pause, document.hidden, the full dispose
  chain), the WebGL-unavailable fallback card, the raycast selection
  lane, the frame playback lane, and the required display-bond honesty
  note (an empty note throws);
* the workspace wiring: the docking page's ligand (artifact raw lane)
  + receptor (pasted text) 3D cards inside the Visualize stage, the MD
  page's trajectory playback card inside the Validate stage, and the
  two honesty notes verbatim;
* the genuine-3D-only rule: ``three`` is imported by exactly ONE
  source file (the shared viewer) — the 2D lanes stay Plotly, and the
  pages never import three directly;
* the package pin: ``three@^0.180.0`` declared and actually imported
  (closing the installed-but-unused state this round found).
"""

from __future__ import annotations

