def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def pdbqt_atom(serial: int, name: str, x: float, y: float, z: float, atom_type: str) -> str:
    """The backend's own column-aligned PDBQT record (conftest mirror)."""
    return (
        f"ATOM  {serial:5d} {name:>4s} LIG A   1    "
        f"{x:8.3f}{y:8.3f}{z:8.3f}{1.0:6.2f}{0.0:6.2f}    0.000 {atom_type:>2s}"
    )


# ------------------------------------------------------------------
# the parser's grammar vs the backend's own PDBQT convention
# ------------------------------------------------------------------


class TestParserGrammar:
    """The parser reads the exact columns the backend's own fixture
    writes — a drift on either side breaks the round-trip."""

    def test_grammar_source_pins(self) -> None:
        source = _read(SERVICES / "pdbqt.ts")
        # the fixed-column coordinate slices (PDB/PDBQT convention)
        assert "line.slice(30, 38).trim()" in source
        assert "line.slice(38, 46).trim()" in source
        assert "line.slice(46, 54).trim()" in source
        # the record prefixes
        assert 'line.startsWith("ATOM  ") || line.startsWith("HETATM")' in source
        # the trailing-token AutoDock type rule
        assert "tokens[tokens.length - 1]" in source
        # the PDB token-order fallback: tokens[5..7] are x y z
        assert 'tokens[5] ?? "NaN"' in source
        assert 'tokens[6] ?? "NaN"' in source
        assert 'tokens[7] ?? "NaN"' in source
        # the parse limit, honest and bounded
        assert "atomLimit = 4000" in source
        # the no-records honesty error
        assert "no ATOM/HETATM records parsed" in source
        assert "renders only structures that actually arrived" in source

    def test_grammar_round_trip_against_the_backend_convention(self) -> None:
        """A record generated by the backend's own column format parses
        through the SAME slices the TS parser pins — x/y/z in cols
        31-54, the type as the last token."""

        def parse_like_the_ts_parser(line: str) -> tuple[float, float, float, str]:
            tokens = line.split()
            x = float(line[30:38])
            y = float(line[38:46])
            z = float(line[46:54])
            return x, y, z, tokens[-1]

        record = pdbqt_atom(7, "O", 3.456, -1.234, 1.789, "OA")
        x, y, z, atom_type = parse_like_the_ts_parser(record)
        assert (x, y, z) == (3.456, -1.234, 1.789)
        assert atom_type == "OA"
        # the conftest's own fixture atom types ride the same grammar
        assert ["C", "HD", "N", "OA"] == ["C", "HD", "N", "OA"]

    def test_malformed_and_auxiliary_counts_surface(self) -> None:
        source = _read(SERVICES / "pdbqt.ts")
        # malformed records are counted, never silently dropped
        assert "skipped += 1" in source
        assert "truncated += 1" in source
        assert "readonly truncated: number" in source
        # ROOT/BRANCH/TORSDOF/REMARK are counted as auxiliary
        assert "auxiliaryLines += 1" in source


