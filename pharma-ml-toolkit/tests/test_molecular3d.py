class TestGenuine3dOnly:
    def test_three_imported_by_exactly_one_source_file(self) -> None:
        importers: list[Path] = []
        for path in SRC.rglob("*.*"):
            if path.suffix not in {".ts", ".tsx"}:
                continue
            text = _read(path)
            if 'from "three"' in text or 'from "three/addons' in text:
                importers.append(path)
        assert importers == [COMPONENTS / "Molecule3D.tsx"], (
            "three must stay imported by exactly the shared viewer — "
            f"drifted to: {[str(p) for p in importers]}"
        )

    def test_pages_import_the_component_not_three(self) -> None:
        for page in (FEATURES / "docking" / "DockingPage.tsx", FEATURES / "md" / "MDPage.tsx"):
            source = _read(page)
            assert 'from "three"' not in source
            assert "@/components/molecular3d/Molecule3D" in source

    def test_2d_lanes_stay_plotly(self) -> None:
        """Phase Eighteen's rule: do not use Three.js for every chart —
        the 2D figure lanes stay the §17 artifact stack."""
        docking = _read(FEATURES / "docking" / "DockingPage.tsx")
        md = _read(FEATURES / "md" / "MDPage.tsx")
        assert "poseAffinityFigure" in docking  # the §11.5 2D figure lane intact
        assert "mdApi.mdSeries" in md  # the §11.7 2D figure lane intact

    def test_package_pin_and_real_usage(self) -> None:
        manifest = json.loads((FRONTEND / "package.json").read_text(encoding="utf-8"))
        assert manifest["dependencies"]["three"] == "^0.180.0"
        # and the dependency is actually used now (the installed-but-
        # unused state this round inherited is closed)
        viewer = _read(COMPONENTS / "Molecule3D.tsx")
        assert 'import * as THREE from "three";' in viewer


