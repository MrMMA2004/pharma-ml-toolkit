    def test_inline_sample_follows_the_parser_grammar(self) -> None:
        """(r288, caught live by the 3D lane's E2E) the inline stack's
        default sample must parse through the page's own
        one-triple-per-line grammar: the shipped sample once carried
        four atoms' 12 numbers on ONE line and could never validate."""
        source = _read(FEATURES / "md" / "MDPage.tsx")
        after = source.split("const SAMPLE_COORDS = [", 1)[1]
        block = after.split('].join("\\n\\n");', 1)[0]
        triples = re.findall(r'"((?:[0-9.]+\s+){2}[0-9.]+)"', block)
        assert len(triples) == 12, (
            f"the inline sample lost the 3 frames × 4 atoms shape: {len(triples)} triples"
        )
        for triple in triples:
            cells = triple.split()
            assert len(cells) == 3, (
                f"a sample line carries {len(cells)} cells, the grammar demands exactly 3"
            )
            assert all(re.fullmatch(r"[0-9.]+", cell) for cell in cells)


