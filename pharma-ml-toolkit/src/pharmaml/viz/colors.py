"""Color parsing, colormaps and palettes -- matplotlib, bokeh and plotly's
data layer, absorbed natively (100x-170).

The five visualization repositories were reviewed file by file; the
color *data and arithmetic* they all share lands here as pure
NumPy/stdlib code so nothing new needs installing:

* **matplotlib** (``lib/matplotlib/colors.py``) -- the conversion
  contract (:func:`to_rgb` / :func:`to_hex` accept ``#rgb``/``#rgba``/
  ``#rrggbb``/``#rrggbbaa`` hex, ``rgb(...)`` strings, 0-1 tuples and
  the 158 embedded named colors) and the 256-step perceptual lookup
  tables (viridis/plasma/inferno/magma/cividis, CC0) with the exact
  quantization rule ``Colormap.__call__`` uses (``int(x*N)``, with
  ``x == 1`` folding onto the last entry).
* **bokeh** (``src/bokeh/transform.py`` + ``palettes.py``) -- the
  color-mapper transforms evaluated for real: :func:`linear_cmap` /
  :func:`log_cmap` follow ``LinearColorMapper``/``LogColorMapper``
  semantics (clamp below/above the range onto the end colors unless
  ``low_color``/``high_color`` override, ``nan_color`` default gray),
  :func:`factor_cmap` cycles factors through a palette, and the
  palette resamplers mirror ``linear_palette`` (index sampling) and
  ``interp_palette`` (per-channel ``np.interp``).
* **plotly.py** (``_plotly_utils/colors/__init__.py``) --
  :func:`find_intermediate_color` linear interpolation,
  :func:`make_colorscale` (evenly spaced ``[[position, color]]``
  pairs) and :func:`sample_colorscale` (bisect between control
  points, exactly plotly's loop).
* **seaborn** (``seaborn/utils.py``) -- :func:`relative_luminance`
  (the W3C formula) rides along for text-on-color decisions.

The embedded data tables live in :mod:`pharmaml.viz._palette_data`
(generated by ``scratch/extract_viz_data_170.py`` with per-source
attribution; CC0 / Apache-2.0 / BSD / MIT terms all recorded there).

Examples
--------
>>> from pharmaml.viz.colors import (
...     NAMED_COLORS, PERCEPTUAL_CMAPS, factor_cmap, linear_cmap,
...     make_colorscale, resample_palette, sample_colorscale, to_hex,
...     to_rgb,
... )
>>> to_rgb("#ff0000")
(1.0, 0.0, 0.0)
>>> to_hex((1.0, 0.5, 0.25))
'#ff8040'
>>> to_rgb("steelblue") == to_rgb(NAMED_COLORS["steelblue"])
True
>>> linear_cmap([0.0, 0.5, 1.0], ("#000000", "#808080", "#ffffff"), low=0.0, high=1.0)
['#000000', '#808080', '#ffffff']
>>> linear_cmap([-1.0, 2.0], ("#000000", "#ffffff"), low=0.0, high=1.0)
['#000000', '#ffffff']
>>> factor_cmap(["a", "b", "c", "a"], ("#111111", "#222222"))
['#111111', '#222222', '#111111', '#111111']
>>> five = resample_palette(PERCEPTUAL_CMAPS["viridis"], 5)
>>> len(five), five[0] == PERCEPTUAL_CMAPS["viridis"][0]
(5, True)
>>> scale = make_colorscale(("#000000", "#ffffff"))
>>> scale[0]
[0.0, '#000000']
>>> sample_colorscale(scale, [0.0, 1.0])
['#000000', '#ffffff']
"""

