_BAD_COLOR = "#808080"  # matplotlib's default bad color, gray


def hex_to_rgb(color: str) -> tuple[float, float, float]:
    """``#rgb``/``#rgba``/``#rrggbb``/``#rrggbbaa`` -> 0-1 RGB triple.

    Follows matplotlib's ``_to_rgba_no_colorcycle`` shorthand rules
    (``#abc`` expands per nibble; the alpha nibble is dropped here).
    """
    text = color.strip()
    if not text.startswith("#") or len(text) not in (4, 5, 7, 9):
        raise ValueError(f"invalid hex color {color!r}")
    digits = text[1:]
    if len(digits) in (3, 4):
        digits = "".join(ch * 2 for ch in digits[:3])
    values = [int(digits[i : i + 2], 16) / 255.0 for i in (0, 2, 4)]
    return (values[0], values[1], values[2])


def rgb_to_hex(rgb: tuple[float, float, float]) -> str:
    """0-1 RGB triple -> ``#rrggbb`` (matplotlib's ``to_hex`` rounding)."""
    return "#{:02x}{:02x}{:02x}".format(
        *(int(round(min(max(c, 0.0), 1.0) * 255)) for c in rgb[:3])  # noqa: RUF046 (np.float64)
    )


def to_rgb(color: object) -> tuple[float, float, float]:
    """Normalize any accepted color form to a 0-1 RGB triple.

    Accepted: hex strings (with/without ``#``, 3/4/6/8 digits),
    ``rgb(r, g, b)`` strings with 0-255 integers, 3/4-element tuples or
    lists of floats, NumPy color-ish arrays, and the 158 embedded named
    colors (CSS4 plus TABLEAU; the ``tab:`` prefix is stripped).
    """
    if isinstance(color, str):
        text = color.strip().lower()
        text = text.removeprefix("tab:")
        if text in NAMED_COLORS:
            return hex_to_rgb(NAMED_COLORS[text])
        if text.startswith("#"):
            return hex_to_rgb(text)
        if text.startswith("rgb(") and text.endswith(")"):
            parts = [float(p) for p in text[4:-1].split(",")[:3]]
            return tuple(p / 255.0 for p in parts)  # type: ignore[return-value]
        if text.startswith("(") and text.endswith(")"):
            return to_rgb(text[1:-1].split(","))
        raise ValueError(f"unknown color name or format: {color!r}")
    if isinstance(color, (tuple, list, np.ndarray)):
        values = [float(v) for v in list(color)[:3]]
        if len(values) < 3:
            raise ValueError(f"color needs three channels: {color!r}")
        return (values[0], values[1], values[2])
    raise ValueError(f"unsupported color: {color!r}")


def to_hex(color: object, keep_alpha: bool = False) -> str:
    """Any accepted color -> ``#rrggbb`` (``#rrggbbAA`` with alpha kept)."""
    rgb = to_rgb(color)
    if not keep_alpha:
        return rgb_to_hex(rgb)
    alpha = 1.0
    if isinstance(color, (tuple, list, np.ndarray)) and len(list(color)) >= 4:
        alpha = float(list(color)[3])
    # int() is load-bearing: round(np.float64) stays np.float64
    return rgb_to_hex(rgb) + f"{int(round(min(max(alpha, 0.0), 1.0) * 255)):02x}"  # noqa: RUF046


def named_color(name: str) -> str:
    """Look one embedded color name up (CSS4 + TABLEAU), hex returned."""
    key = name.strip().lower()
    key = key.removeprefix("tab:")
    if key not in NAMED_COLORS:
        raise ValueError(
            f"unknown color name {name!r}; the embedded tables carry "
            f"{len(NAMED_COLORS)} CSS4/TABLEAU names"
        )
    return NAMED_COLORS[key]


def find_intermediate_color(
    lowcolor: object, highcolor: object, intermed: float
) -> tuple[float, float, float]:
    """plotly.py's ``find_intermediate_color``: linear per-channel blend.

    ``intermed`` 0 returns ``lowcolor``'s channels, 1 ``highcolor``'s.
    """
    low = np.asarray(to_rgb(lowcolor), dtype=float)
    high = np.asarray(to_rgb(highcolor), dtype=float)
    blended = low + float(intermed) * (high - low)
    return (float(blended[0]), float(blended[1]), float(blended[2]))


def relative_luminance(color: object) -> float:
    """W3C relative luminance (seaborn ``utils.relative_luminance``).

    Used to pick black/white text on a filled swatch.
    """
    rgb = to_rgb(color)
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return float(0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2])


def resample_palette(
    palette: object, n_colors: int, method: str = "interp"
) -> tuple[str, ...]:
    """Resample a hex palette to ``n_colors`` (bokeh's two flavors).

    ``method="interp"`` is bokeh's ``interp_palette``: per-channel
    ``np.interp`` over the 0-1 span, so endpoints are kept exactly and
    interior colors are blended.  ``method="linear"`` is bokeh's
    ``linear_palette``: pure index subsampling
    ``floor(linspace(0, len-1, n))`` -- no blending, duplicates when
    ``n > len``.
    """
    colors = [to_hex(c) for c in _as_palette(palette)]
    n = int(n_colors)
    if n < 1:
        raise ValueError("n_colors must be >= 1")
    if n <= len(colors) and method == "linear":
        idx = np.floor(np.linspace(0, len(colors) - 1, n)).astype(int)
        return tuple(colors[i] for i in idx)
    if n == 1:
        return (colors[0],)
    if method == "linear":
        idx = np.floor(np.linspace(0, len(colors) - 1, n)).astype(int)
        return tuple(colors[i] for i in idx)
    rgb = np.array([hex_to_rgb(c) for c in colors], dtype=float)
    pos = np.linspace(0.0, 1.0, n)
    span = np.linspace(0.0, 1.0, len(colors))
    blended = np.column_stack([np.interp(pos, span, rgb[:, ch]) for ch in range(3)])
    return tuple(rgb_to_hex(tuple(row)) for row in blended)


class ColorMap:
    """A discrete hex lookup table with matplotlib's call contract.

    ``cmap(values)`` maps 0-1 floats onto palette entries using
    matplotlib's ``Colormap.__call__`` quantization (``int(x * N)``,
    with ``x == 1`` folded onto the last entry) but bokeh's
    out-of-range contract: values below ``low`` clamp onto the first
    color (or ``low_color``), above ``high`` onto the last (or
    ``high_color``), and NaN maps onto ``nan_color`` (gray, matching
    both libraries' default).
    """

    def __init__(
        self,
        palette: object,
        name: str = "custom",
        *,
        nan_color: str = _BAD_COLOR,
    ) -> None:
        colors = [to_hex(c) for c in _as_palette(palette)]
        if not colors:
            raise ValueError("a colormap needs at least one color")
        self.colors: tuple[str, ...] = tuple(colors)
        self.name = name
        self.nan_color = nan_color

    def __len__(self) -> int:
        return len(self.colors)

    def __repr__(self) -> str:  # pragma: no cover - cosmetic
        return f"ColorMap({self.name!r}, {len(self.colors)} colors)"

    def __call__(
        self,
        values: object,
        *,
        low: float | None = None,
        high: float | None = None,
        low_color: str | None = None,
        high_color: str | None = None,
    ) -> list[str]:
        """Map ``values`` (raw data, not 0-1) through the table.

        ``low``/``high`` default to 0/1 (normalized input); pass a data
        range to use the table as bokeh's ``linear_cmap`` does.
        """
        arr = np.asarray(values, dtype=float)
        lo = 0.0 if low is None else float(low)
        hi = 1.0 if high is None else float(high)
        if hi <= lo:
            raise ValueError("high must be greater than low")
        scaled = (arr - lo) / (hi - lo)
        out: list[str] = []
        n = len(self.colors)
        for value in np.atleast_1d(scaled).ravel():
            if not np.isfinite(value):
                out.append(self.nan_color)
                continue
            index = int(value * n)
            if index >= n:  # matplotlib folds x == 1 onto the last entry
                index = n - 1
            if index < 0:
                out.append(low_color or self.colors[0])
            elif index >= n:
                out.append(high_color or self.colors[-1])
            else:
                out.append(self.colors[index])
        return out

    def resampled(self, n_colors: int) -> ColorMap:
        """bokeh's ``interp_palette`` resample, as a new ColorMap."""
        return ColorMap(resample_palette(self.colors, n_colors), name=f"{self.name}_res{int(n_colors)}")

    def reversed(self) -> ColorMap:
        """The ``_r`` twin (matplotlib's ``reversed()`` for listed maps)."""
        return ColorMap(tuple(reversed(self.colors)), name=f"{self.name}_r")


def _as_palette(palette: object) -> list[object]:
    if isinstance(palette, str):
        if palette in PERCEPTUAL_CMAPS:
            return list(PERCEPTUAL_CMAPS[palette])
        if palette in TAB_CMAPS:
            return list(TAB_CMAPS[palette])
        if palette in BREWER:
            return list(BREWER[palette])
        raise ValueError(f"unknown palette name {palette!r}")
    if isinstance(palette, (tuple, list, np.ndarray)):
        return list(palette)
    raise ValueError(f"unsupported palette: {palette!r}")


def linear_cmap(
    values: object,
    palette: object,
    low: float,
    high: float,
    *,
    low_color: str | None = None,
    high_color: str | None = None,
    nan_color: str = _BAD_COLOR,
) -> list[str]:
    """bokeh's ``transform.linear_cmap`` evaluated as real colors.

    Maps ``values`` in ``[low, high]`` onto ``palette`` linearly,
    clamping out-of-range values onto the end colors (bokeh's
    ``LinearColorMapper`` contract: ``low_color``/``high_color``
    override, ``nan_color`` default gray).
    """
    return ColorMap(_as_palette(palette), nan_color=nan_color)(
        values, low=low, high=high, low_color=low_color, high_color=high_color
    )


def log_cmap(
    values: object,
    palette: object,
    low: float,
    high: float,
    *,
    low_color: str | None = None,
    high_color: str | None = None,
    nan_color: str = _BAD_COLOR,
) -> list[str]:
    """bokeh's ``transform.log_cmap``: the mapping happens on ``ln`` scale.

    ``low`` must be > 0 (bokeh's ``LogColorMapper`` rejects
    non-positive ranges); breaks land at ``e**k`` boundaries.
    """
    if low <= 0 or high <= 0:
        raise ValueError("log_cmap needs positive low and high (bokeh's LogColorMapper)")
    arr = np.asarray(values, dtype=float)
    log_values = np.where(np.isfinite(arr) & (arr > 0), np.log(np.where(arr > 0, arr, 1.0)), np.nan)
    return ColorMap(_as_palette(palette), nan_color=nan_color)(
        log_values, low=float(np.log(low)), high=float(np.log(high)),
        low_color=low_color, high_color=high_color,
    )


def factor_cmap(
    factors: Sequence[Any],
    palette: object,
    start: int = 0,
    end: int | None = None,
    nan_color: str = _BAD_COLOR,
) -> list[str]:
    """bokeh's ``transform.factor_cmap``: factors cycle through the palette.

    ``start``/``end`` slice multi-level factor tuples first (bokeh maps
    on ``factor[start:end]``); unknown factors take ``nan_color``.
    """
    colors = [to_hex(c) for c in _as_palette(palette)]
    out: list[str] = []
    for factor in list(factors):
        if isinstance(factor, tuple):
            key = factor[start : end if end is not None else len(factor)]
        else:
            key = factor
        text = key if isinstance(key, str) else str(key)
        if text is None or text == "":
            out.append(nan_color)
            continue
        # cycle by first-appearance order, like the mapper's factor dict
        out.append(colors[(_factor_rank(factors, text)) % len(colors)])
    return out


def _factor_rank(factors: Sequence[Any], value: str) -> int:
    seen: list[str] = []
    for factor in list(factors):
        text = factor if isinstance(factor, str) else str(factor)
        if text not in seen:
            seen.append(text)
    return seen.index(value)


def make_colorscale(colors: object) -> list[list[object]]:
    """plotly's ``make_colorscale``: colors -> evenly spaced ``[[pos, hex]]``.

    A colorscale is plotly's continuous-color contract; bare color
    lists are promoted exactly the way ``plotly.colors.make_colorscale``
    does (``i / (n - 1)`` positions).
    """
    hexes = [to_hex(c) for c in _as_palette(colors)]
    if len(hexes) == 1:
        return [[0.0, hexes[0]]]
    return [[i / (len(hexes) - 1), hexes[i]] for i in range(len(hexes))]


def sample_colorscale(
    colorscale: Any, samplepoints: Any, low: float = 0.0, high: float = 1.0
) -> list[str]:
    """plotly's ``sample_colorscale``: positions -> interpolated hexes.

    Accepts a ``[[position, color]]`` scale (or a bare palette, which
    is promoted).  Each point is bisected between its bracketing
    control points and linearly blended -- plotly's exact loop, minus
    the rgb-string relabeling (hex out).
    """
    scale = colorscale
    if not (isinstance(scale, list) and scale and isinstance(scale[0], (list, tuple))):
        scale = make_colorscale(scale)
    positions = [float(str(item[0])) for item in scale]
    hexes = [to_hex(item[1]) for item in scale]
    if positions != sorted(positions) or len(set(positions)) != len(positions):
        raise ValueError("colorscale positions must be strictly increasing")
    out: list[str] = []
    lo, hi = float(low), float(high)
    for raw in np.atleast_1d(np.asarray(samplepoints, dtype=float)).ravel():
        point = (float(raw) - lo) / (hi - lo) if hi != lo else 0.0
        if point <= positions[0]:
            out.append(hexes[0])
            continue
        if point >= positions[-1]:
            out.append(hexes[-1])
            continue
        import bisect

        high_idx = bisect.bisect_left(positions, point)
        low_idx = high_idx - 1
        span = positions[high_idx] - positions[low_idx]
        frac = (point - positions[low_idx]) / span if span else 0.0
        out.append(rgb_to_hex(find_intermediate_color(hexes[low_idx], hexes[high_idx], frac)))
    return out
