"""The best-of-ml-python catalogue: the ML landscape as queryable data.

``lukasmasuch/best-of-ml-python`` was reviewed file by file for this
module: ``projects.yaml`` (the source of truth -- 34 category
definitions plus the 929 curated project entries), the rendered
``README.md`` (the ranked list the repository exists to publish), the
weekly ``history/*.csv`` snapshots that give every project its
stars / license / description at a pinned date, ``config/header.md``
and ``config/footer.md``, ``latest-changes.md`` and
``CONTRIBUTING.md``.  The snapshot embedded here is
``2025-10-30_projects.csv``: **924 projects** (858 across the 34
declared categories plus the 66 the generator files under *Others*),
**5,121,472 stars**, grouped into **35 browsable sections**.

What the catalogue gives the toolkit is the answer to "which library
should I use for X?" offline: every category, every project, its
one-line description, license, star count and best-of score, with
search and ranking on top:

* :func:`catalog_categories` -- the 35 sections with live counts.
* :func:`catalog_projects` -- one category's projects (or all 924),
  best-of score descending.
* :func:`search_catalog` -- case-insensitive substring search over
  names and descriptions, score-ranked.
* :func:`catalog_top` -- the head of a category (or of everything).
* :func:`catalog_summary` -- the snapshot's headline numbers plus the
  license distribution.
* :func:`coverage_table` -- the honest audit: for each of the 34
  categories, whether this toolkit implements the concept natively
  (and in which module), partially, deliberately leaves it to external
  engines, or files it out of scope for a pharma-ML desktop tool.

The audit's verdicts are stated, not implied.  Five categories gained
native surfaces in this round -- privacy-ml (:mod:`pharmaml.ml.privacy`),
recommender-systems (:mod:`pharmaml.ml.recommend`),
nn-search (:mod:`pharmaml.ml.annsearch`), adversarial
(:mod:`pharmaml.ml.adversarial`) and time-series-data
(:mod:`pharmaml.ml.timeseries`) -- which is what "add the missing
items" means for a catalogue repository: not vendoring 924 libraries,
but closing the capability gaps the catalogue exposes.

Attribution and license, stated once: the project metadata below is
a snapshot of the best-of-ml-python collection, (c) its contributors,
distributed by them under CC-BY-SA-4.0; this module embeds that
snapshot with attribution for offline reference, alongside the
toolkit's MIT code.

Examples
--------
>>> from pharmaml.ml.catalog import (
...     catalog_categories, catalog_summary, catalog_top, search_catalog,
... )
>>> summary = catalog_summary()
>>> summary.n_projects
924
>>> summary.n_categories
35
>>> summary.snapshot
'2025-10-30'
>>> catalog_categories()[0].slug
'ml-frameworks'
>>> hits = search_catalog("differential privacy")
>>> hits[0].name
'Opacus'
>>> top = catalog_top(n=1)
>>> top[0].name
'Tensorflow'
"""

