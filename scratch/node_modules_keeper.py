#!/usr/bin/env python
"""round-275 -- the node_modules keeper.  The sandbox's janitor wipes
node_modules (and ONLY node_modules — zips/scratch/untracked files all
survive) on a ~1-3 minute cadence when the directory is not being
actively accessed; the r275 E2E needs the dev server up for minutes.
This double-forked daemon (the dev_daemon recipe: grandchild reparents
to PID 1, immune to the per-call subtree reaping) touches the
directory every 5 s to keep it 'in use'.  Usage:

    python3 scratch/node_modules_keeper.py start|stop
"""
from __future__ import annotations

import os
import sys
import time
from pathlib import Path

NM = Path("/home/z/my-project/node_modules")
STAMP = NM / ".r275-keeper"
PIDFILE = Path("/tmp/nm_keeper.pid")


def main() -> None:  # the reparented grandchild
    PIDFILE.write_text(str(os.getpid()))
    while True:
        try:
            if NM.is_dir():
                STAMP.touch(exist_ok=True)
                os.utime(NM)  # the dir mtime too
        except OSError:
            pass
        time.sleep(5)


def start() -> int:
    if os.fork() > 0:
        return 0
    os.setsid()
    if os.fork() > 0:
        os._exit(0)
    devnull = os.open(os.devnull, os.O_RDWR)
    os.dup2(devnull, 0), os.dup2(devnull, 1), os.dup2(devnull, 2)
    main()
    return 0


def stop() -> int:
    try:
        pid = int(PIDFILE.read_text().strip())
        os.kill(pid, 15)
        PIDFILE.unlink(missing_ok=True)
        print(f"keeper: stopped ({pid})")
    except (OSError, ValueError):
        print("keeper: not running")
    return 0


if __name__ == "__main__":
    sys.exit({"start": start, "stop": stop}[
        sys.argv[1] if len(sys.argv) > 1 else "start"
    ]())
