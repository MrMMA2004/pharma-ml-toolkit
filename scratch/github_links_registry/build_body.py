class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))


def heading(text, style, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


H1_ORPHAN = (PAGE_H - TOP_MARGIN - BOTTOM_MARGIN) * 0.18


def major_section(text, first_flowables):
    """H1 with orphan prevention; heading kept with its first content."""
    out = [CondPageBreak(H1_ORPHAN)]
    out.append(KeepTogether([heading(text, h1, level=0)] + first_flowables[:1]))
    out.extend(first_flowables[1:])
    return out


def sub_section(text, first_flowables):
    out = [CondPageBreak(H1_ORPHAN * 0.6)]
    out.append(KeepTogether([heading(text, h2, level=1)] + first_flowables[:1]))
    out.extend(first_flowables[1:])
    return out


