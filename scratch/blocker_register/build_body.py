def callout(story, stats):
    """Row of stat callout boxes. stats = [(big, label, color)]"""
    n = len(stats)
    cells = []
    for big, label, col in stats:
        inner = Table(
            [[Paragraph("<b>%s</b>" % big,
                        ParagraphStyle("st", parent=S_STAT, textColor=col))],
             [Paragraph(label, S_STATLBL)]],
            colWidths=[AVAIL_W / n - 12])
        inner.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("BOX", (0, 0), (-1, -1), 0.8, BORDER),
            ("TOPPADDING", (0, 0), (-1, 0), 8),
            ("BOTTOMPADDING", (0, -1), (-1, -1), 8),
            ("TOPPADDING", (0, 1), (-1, 1), 2),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        cells.append(inner)
    outer = Table([cells], colWidths=[AVAIL_W / n] * n, hAlign="CENTER")
    outer.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.extend(safe_keep([outer]))
    story.append(Spacer(1, 10))


def mk_table(story, header, rows, ratios, caption=None, td_styles=None):
    """Standard striped table. header = [str], rows = [[str]]."""
    col_w = [r * AVAIL_W for r in ratios]
    data = [[Paragraph("<b>%s</b>" % h, S_TH) for h in header]]
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            st = (td_styles or {}).get(i, S_TD)
            cells.append(Paragraph(c, st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                     TABLE_ROW_EVEN if i % 2 else TABLE_ROW_ODD))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 10))
    story.append(t)
    if caption:
        story.append(Paragraph(caption, S_CAPTION))
    story.append(Spacer(1, 10))


