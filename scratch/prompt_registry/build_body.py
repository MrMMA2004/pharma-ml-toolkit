def esc(t):
    _amp = chr(38)
    return (
        t.replace(_amp, _amp + "amp;")
        .replace("<", _amp + "lt;")
        .replace(">", _amp + "gt;")
        .replace('"', _amp + "quot;")
    )


def q(t):
    """A verbatim prompt quote cell."""
    return Paragraph("<i>\u201c%s\u201d</i>" % esc(t), cell_quote)


