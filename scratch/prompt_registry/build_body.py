class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            level = getattr(flowable, "bookmark_level", 0)
            text = getattr(flowable, "bookmark_text", "")
            key = getattr(flowable, "bookmark_key", "")
            self.notify("TOCEntry", (level, text, self.page, key))


def heading(text, style, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


H1_ORPHAN = (PAGE_H - TOP_MARGIN - BOTTOM_MARGIN) * 0.18


def major_section(text, first_flowables):
    out = [CondPageBreak(H1_ORPHAN)]
    out.append(KeepTogether([heading(text, h1, level=0)] + first_flowables[:1]))
    out.extend(first_flowables[1:])
    return out


def sub_section(text, first_flowables):
    out = [CondPageBreak(H1_ORPHAN * 0.6)]
    out.append(KeepTogether([heading(text, h2, level=1)] + first_flowables[:1]))
    out.extend(first_flowables[1:])
    return out


def base_table_style(n_rows):
    st = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
    ]
    for r in range(1, n_rows):
        st.append(("BACKGROUND", (0, r), (-1, r), TABLE_ROW_ODD if r % 2 == 0 else TABLE_ROW_EVEN))
    return TableStyle(st)


def era_table(rows, col_ratios):
    """rows: list of (num, quote, given_in, outcome). col_ratios sum to 1.0."""
    header = [
        Paragraph("<b>#</b>", cell_hdr),
        Paragraph("<b>The prompt</b>", cell_hdr),
        Paragraph("<b>Given in</b>", cell_hdr),
        Paragraph("<b>What it produced</b>", cell_hdr),
    ]
    data = [header]
    for n, text, given, outcome in rows:
        data.append([
            Paragraph(str(n), cell_num),
            q(text),
            Paragraph(given, cell_txt),
            Paragraph(outcome, cell_txt),
        ])
    widths = [AVAIL * r for r in col_ratios]
    assert abs(sum(widths) - AVAIL) < 1.0
    tbl = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    tbl.setStyle(base_table_style(len(data)))
    return tbl


