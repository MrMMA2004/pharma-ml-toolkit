import { promises as fs } from "fs";
import path from "path";
import { NextResponse } from "next/server";
import { TOOLKIT_ROOT } from "@/lib/toolkit-fs";
import type {
  ReferenceModule,
  ReferenceResponse,
  ReferenceSymbol,
  SymbolKind,
} from "@/lib/toolkit-types";

export const dynamic = "force-dynamic";

/** Tiny in-memory TTL cache (mirrors the tree route). */
const CACHE_TTL_MS = 60_000;
let cache: { data: ReferenceResponse; expiresAt: number } | null = null;

const VALID_KINDS = new Set<SymbolKind>(["function", "class", "module", "constant"]);

/** Table-row pattern: | `name` | kind | summary | */
const ROW_RE = /^\|\s*`([^`]+)`\s*\|\s*(\w+)\s*\|\s*(.*?)\s*\|$/;
const MODULE_HEADING_RE = /^##\s+`([^`]+)`\s*$/;
const BLURB_RE = /^\*([^*].*)\*$/;

/** Resolve a dotted module name to its toolkit-relative source path. */
async function resolveSourcePath(dotted: string): Promise<string> {
  const base = dotted.split(".").join("/");
  const asFile = `src/${base}.py`;
  const asPackage = `src/${base}/__init__.py`;
  for (const candidate of [asFile, asPackage]) {
    try {
      const stat = await fs.stat(path.join(TOOLKIT_ROOT, candidate));
      if (stat.isFile()) return candidate;
    } catch {
      // candidate does not exist — try the next form
    }
  }
  return "README.md";
}

/** Escape a symbol name for literal use inside a RegExp. */
function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Locate the 1-based definition line of a symbol in a source string.
 * Returns null when the definition is not in this file (e.g. re-exported
 * from a sub-module) — the caller may then follow the import map.
 */
function findDefinitionLine(source: string, name: string, kind: SymbolKind): number | null {
  const escaped = escapeRegExp(name);
  let pattern: RegExp;
  if (kind === "class") {
    pattern = new RegExp(`^class\\s+${escaped}\\b`);
  } else if (kind === "function") {
    pattern = new RegExp(`^(async\\s+)?def\\s+${escaped}\\b`);
  } else if (kind === "constant") {
    pattern = new RegExp(`^${escaped}\\s*[:=]`);
  } else {
    // Re-exported sub-module: `from . import x` / `from .x import y as x`
    pattern = new RegExp(`^from\\s+\\S+\\s+import\\s+.*\\b${escaped}\\b`);
  }
  const lines = source.split("\n");
  for (let i = 0; i < lines.length; i++) {
    if (pattern.test(lines[i] ?? "")) return i + 1;
  }
  return null;
}

/** Convert a (possibly relative) dotted import to a toolkit source path. */
function dottedToSourcePath(
  dotted: string,
  moduleDotted: string,
  moduleSourcePath: string
): string | null {
  let absolute: string;
  if (dotted.startsWith(".")) {
    const isPackageInit = moduleSourcePath.endsWith("__init__.py");
    const pkgDotted = isPackageInit
      ? moduleDotted
      : moduleDotted.split(".").slice(0, -1).join(".");
    const baseParts = pkgDotted ? pkgDotted.split(".") : [];
    const leading = dotted.length - dotted.replace(/^\.+/, "").length;
    const up = leading - 1;
    if (up < 0 || up > baseParts.length) return null;
    const parts = [...baseParts.slice(0, baseParts.length - up), dotted.replace(/^\.+/, "")];
    absolute = parts.filter((p) => p.length > 0).join(".");
  } else {
    absolute = dotted;
  }
  if (!absolute.startsWith("pharmaml")) return null;
  return `src/${absolute.split(".").join("/")}.py`;
}

/**
 * Parse `from <module> import a, b, (c, d)` statements into a map of
 * imported symbol name → candidate source file path. Handles both
 * absolute (`from pharmaml.chem.converters import …`) and relative
 * (`from .converters import …`) forms, including multi-line parenthesized
 * name lists.
 */
function parseImportMap(
  source: string,
  moduleDotted: string,
  moduleSourcePath: string
): Map<string, string> {
  const map = new Map<string, string>();
  const lines = source.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? "";
    const match = /^from\s+([\w.]+)\s+import\s*(\(?)(.*)$/.exec(line);
    if (!match) continue;
    const [, dotted, paren, rest] = match;
    let namesText = rest;
    if (paren === "(" && !rest.includes(")")) {
      const collected: string[] = [rest];
      for (let j = i + 1; j < lines.length; j++) {
        const next = lines[j] ?? "";
        collected.push(next);
        if (next.includes(")")) break;
      }
      namesText = collected.join(" ");
    }
    const names = namesText
      .replace(/[()\\]/g, "")
      .split(",")
      .map((n) => n.trim().split(/\s+as\s+/)[0]?.trim() ?? "")
      .filter((n) => /^\w+$/.test(n));
    const filePath = dottedToSourcePath(dotted, moduleDotted, moduleSourcePath);
    if (!filePath) continue;
    for (const name of names) map.set(name, filePath);
  }
  return map;
}

/**
 * Parse docs/INDEX.md into a structured module/symbol listing.
 * The file is generated by scratch/build_docs_index.py from each
 * module's __all__ exports, so this parser only needs to handle
 * that one well-defined shape.
 */
async function parseReference(): Promise<ReferenceResponse> {
  const indexPath = path.join(TOOLKIT_ROOT, "docs", "INDEX.md");
  let raw: string;
  try {
    raw = await fs.readFile(indexPath, "utf8");
  } catch {
    throw new Error(
      "docs/INDEX.md is missing — regenerate it with `python scratch/build_docs_index.py`."
    );
  }

  const modules: ReferenceModule[] = [];
  let current: { name: string; blurb: string; symbols: ReferenceSymbol[] } | null = null;

  for (const line of raw.split("\n")) {
    const heading = MODULE_HEADING_RE.exec(line);
    if (heading) {
      if (current) modules.push(await finalizeModule(current));
      current = { name: heading[1], blurb: "", symbols: [] };
      continue;
    }
    if (!current) continue;

    const blurb = BLURB_RE.exec(line);
    if (blurb && current.symbols.length === 0 && !current.blurb) {
      current.blurb = blurb[1].trim();
      continue;
    }

    const row = ROW_RE.exec(line);
    if (row) {
      const [, name, kind, summary] = row;
      if (VALID_KINDS.has(kind as SymbolKind)) {
        current.symbols.push({
          name,
          kind: kind as SymbolKind,
          summary: summary.replace(/\s*\|$/, "").trim(),
        });
      }
    }
  }
  if (current) modules.push(await finalizeModule(current));

  const symbols = modules.reduce((acc, m) => acc + m.symbols.length, 0);
  return {
    modules,
    stats: { modules: modules.length, symbols },
    generatedAt: new Date().toISOString(),
  };
}

/** Attach source path, definition line and fallback blurb to each symbol. */
async function finalizeModule(mod: {
  name: string;
  blurb: string;
  symbols: ReferenceSymbol[];
}): Promise<ReferenceModule> {
  const sourcePath = await resolveSourcePath(mod.name);
  let source: string | null = null;
  if (sourcePath !== "README.md") {
    try {
      source = await fs.readFile(path.join(TOOLKIT_ROOT, sourcePath), "utf8");
    } catch {
      source = null; // unreadable file — symbols get no line numbers
    }
  }

  const importMap = source ? parseImportMap(source, mod.name, sourcePath) : new Map<string, string>();
  const subSources = new Map<string, string>();

  const symbols: ReferenceSymbol[] = [];
  for (const sym of mod.symbols) {
    let line = source ? findDefinitionLine(source, sym.name, sym.kind) : null;
    let symPath = sourcePath;

    if (line === null) {
      // Follow the re-export: the symbol is defined in a sub-module.
      const candidate = importMap.get(sym.name);
      if (candidate) {
        let subSource = subSources.get(candidate);
        if (subSource === undefined) {
          try {
            subSource = await fs.readFile(path.join(TOOLKIT_ROOT, candidate), "utf8");
          } catch {
            subSource = null;
          }
          subSources.set(candidate, subSource ?? "");
        }
        if (subSource) {
          const subLine = findDefinitionLine(subSource, sym.name, sym.kind);
          if (subLine !== null) {
            line = subLine;
            symPath = candidate;
          }
        }
      }
    }

    symbols.push({ ...sym, line, sourcePath: symPath });
  }

  return {
    name: mod.name,
    blurb: mod.blurb || "Public API surface",
    sourcePath,
    symbols,
  };
}

export async function GET() {
  try {
    if (cache && cache.expiresAt > Date.now()) {
      return NextResponse.json(cache.data);
    }
    const data = await parseReference();
    cache = { data, expiresAt: Date.now() + CACHE_TTL_MS };
    return NextResponse.json(data);
  } catch (err) {
    return NextResponse.json(
      {
        error: "Failed to build the API reference.",
        detail: err instanceof Error ? err.message : String(err),
      },
      { status: 500 }
    );
  }
}
